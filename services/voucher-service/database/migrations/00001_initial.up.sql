CREATE OR REPLACE FUNCTION set_update_time() RETURNS trigger AS $$
BEGIN
    NEW.update_time = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TYPE voucher_type   AS ENUM ('normal', 'seckill');
CREATE TYPE voucher_status AS ENUM ('active', 'inactive', 'expired');

CREATE TABLE voucher (
    id           bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id      bigint         NOT NULL,          -- no FK: shop lives in shop_db
    title        varchar(255)   NOT NULL,
    sub_title    varchar(255)   NOT NULL DEFAULT '',
    rules        varchar(1024)  NOT NULL DEFAULT '',
    pay_value    bigint         NOT NULL,          -- cents
    actual_value bigint         NOT NULL,          -- cents
    type         voucher_type   NOT NULL DEFAULT 'normal',
    status       voucher_status NOT NULL DEFAULT 'active',
    create_time  timestamptz    NOT NULL DEFAULT now(),
    update_time  timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pay_value_positive    CHECK (pay_value >= 0),
    CONSTRAINT actual_value_positive CHECK (actual_value >= 0)
);

CREATE INDEX idx_voucher_shop_id ON voucher (shop_id);

CREATE TABLE seckill_voucher (
    voucher_id  bigint      PRIMARY KEY REFERENCES voucher (id) ON DELETE CASCADE,
    stock       integer     NOT NULL,
    begin_time  timestamptz NOT NULL,
    end_time    timestamptz NOT NULL,
    create_time timestamptz NOT NULL DEFAULT now(),
    update_time timestamptz NOT NULL DEFAULT now(),
    -- THE failure mode Saga S1 exists to handle. Redis is an optimistic
    -- pre-filter; this constraint is the final arbiter.
    CONSTRAINT stock_not_negative CHECK (stock >= 0),
    CONSTRAINT valid_window       CHECK (end_time > begin_time)
);

CREATE TRIGGER voucher_set_update_time BEFORE UPDATE ON voucher
    FOR EACH ROW EXECUTE FUNCTION set_update_time();
CREATE TRIGGER seckill_voucher_set_update_time BEFORE UPDATE ON seckill_voucher
    FOR EACH ROW EXECUTE FUNCTION set_update_time();
