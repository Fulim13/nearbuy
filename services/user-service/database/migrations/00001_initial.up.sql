CREATE OR REPLACE FUNCTION set_update_time() RETURNS trigger AS $$
BEGIN
    NEW.update_time = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE app_user (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone           varchar(11)  NOT NULL,
    password        varchar(128) NOT NULL DEFAULT '',
    nick_name       varchar(32)  NOT NULL DEFAULT '',
    icon            varchar(255) NOT NULL DEFAULT '',
    city            varchar(32),
    introduce       varchar(128),
    fans            integer      NOT NULL DEFAULT 0,
    followee        integer      NOT NULL DEFAULT 0,
    gender          smallint     NOT NULL DEFAULT 0,
    birthday        date,
    credits         integer      NOT NULL DEFAULT 0,
    level           smallint     NOT NULL DEFAULT 0,
    balance         bigint       NOT NULL DEFAULT 0,
    trading_balance bigint       NOT NULL DEFAULT 0,
    create_time     timestamptz  NOT NULL DEFAULT now(),
    update_time     timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uniq_phone        UNIQUE (phone),
    CONSTRAINT balance_positive  CHECK (balance >= 0),
    CONSTRAINT trading_positive  CHECK (trading_balance >= 0)
);

CREATE TRIGGER app_user_set_update_time BEFORE UPDATE ON app_user
    FOR EACH ROW EXECUTE FUNCTION set_update_time();

CREATE TABLE follow (
    id             bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint      NOT NULL,
    follow_user_id bigint      NOT NULL,
    create_time    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uniq_follow    UNIQUE (user_id, follow_user_id),
    CONSTRAINT no_self_follow CHECK (user_id <> follow_user_id)
);

CREATE INDEX idx_follow_follow_user_id ON follow (follow_user_id);
