CREATE OR REPLACE FUNCTION set_update_time() RETURNS trigger AS $$
BEGIN
    NEW.update_time = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE blog (
    id          bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id     bigint        NOT NULL,   -- no FK: shop lives in shop_db
    user_id     bigint        NOT NULL,   -- no FK: app_user lives in user_db
    title       varchar(255)  NOT NULL,
    images      varchar(2048) NOT NULL DEFAULT '',
    content     text          NOT NULL,
    -- Eventually consistent, folded in by the blog.liked consumer
    -- Redis holds the authoritative like set.
    liked       integer       NOT NULL DEFAULT 0,
    comments    integer       NOT NULL DEFAULT 0,
    create_time timestamptz   NOT NULL DEFAULT now(),
    update_time timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT liked_not_negative CHECK (liked >= 0)
);

CREATE INDEX idx_blog_user_id ON blog (user_id);
CREATE INDEX idx_blog_liked   ON blog (liked DESC, id DESC);

CREATE TRIGGER blog_set_update_time BEFORE UPDATE ON blog
    FOR EACH ROW EXECUTE FUNCTION set_update_time();
