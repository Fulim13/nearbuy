CREATE OR REPLACE FUNCTION set_update_time() RETURNS trigger AS $$
BEGIN
    NEW.update_time = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE shop_type (
    id          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(32)  NOT NULL,
    icon        varchar(255) NOT NULL DEFAULT '',
    sort_order  integer      NOT NULL DEFAULT 0,
    create_time timestamptz  NOT NULL DEFAULT now(),
    update_time timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE shop (
    id          bigint           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(128)     NOT NULL,
    type_id     bigint           NOT NULL REFERENCES shop_type (id),
    images      varchar(2048)    NOT NULL DEFAULT '',
    area        varchar(128),
    address     varchar(255)     NOT NULL,
    x           double precision NOT NULL,
    y           double precision NOT NULL,
    avg_price   bigint           NOT NULL DEFAULT 0,
    sold        integer          NOT NULL DEFAULT 0,
    comments    integer          NOT NULL DEFAULT 0,
    score       integer          NOT NULL DEFAULT 50,
    open_hours  varchar(32),
    create_time timestamptz      NOT NULL DEFAULT now(),
    update_time timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT score_range CHECK (score BETWEEN 0 AND 50),
    CONSTRAINT lon_range   CHECK (x BETWEEN -180 AND 180),
    CONSTRAINT lat_range   CHECK (y BETWEEN -85.05112878 AND 85.05112878)
);

CREATE INDEX idx_shop_type_id ON shop (type_id);
CREATE INDEX idx_shop_area    ON shop (area);

CREATE TRIGGER shop_set_update_time BEFORE UPDATE ON shop
    FOR EACH ROW EXECUTE FUNCTION set_update_time();
CREATE TRIGGER shop_type_set_update_time BEFORE UPDATE ON shop_type
    FOR EACH ROW EXECUTE FUNCTION set_update_time();
